// This smoke test proves that a Connect-ES client generated by protoc-gen-es
// from packages/sandboxd/spec/process/v1/process.proto can complete a real
// gRPC Execute call over h2c through a Kubernetes WebSocket pod port-forward.
// The production PodTunnel, including its lifecycle and backpressure behavior,
// lands with the connect layer in a follow-up PR and is tested there.
//
// It imports the generated stub via a relative path into the SDK's source
// tree (rather than through the published package) because src/_proto is
// deliberately excluded from the SDK's tsc build while nothing in the
// public API references it yet (see src/_proto/README.md).

